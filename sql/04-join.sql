-- 조건에 맞는 도서와 저자 리스트 출력하기: INNER JOIN 기본형
SELECT B.BOOK_ID, A.AUTHOR_NAME, B.PUBLISHED_DATE
FROM BOOK B
JOIN AUTHOR A ON B.AUTHOR_ID = A.AUTHOR_ID
WHERE B.CATEGORY = '경제'
ORDER BY B.PUBLISHED_DATE ASC;

-- 상품 별 오프라인 매출 구하기: JOIN + GROUP BY, 집계함수 안에서 계산식 사용
SELECT P.PRODUCT_CODE, SUM(P.PRICE * O.SALES_AMOUNT) AS SALES
FROM PRODUCT P
JOIN OFFLINE_SALE O ON P.PRODUCT_ID = O.PRODUCT_ID
GROUP BY P.PRODUCT_CODE
ORDER BY SALES DESC, P.PRODUCT_CODE ASC;

-- 없어진 기록 찾기: LEFT JOIN + IS NULL로 "한쪽에만 있는" 데이터 찾기
-- (매입대사로 치면: 세금계산서는 있는데 매입장엔 없는 거래를 찾는 것과 같은 패턴)
SELECT O.ANIMAL_ID, O.NAME
FROM ANIMAL_OUTS O
LEFT JOIN ANIMAL_INS I ON O.ANIMAL_ID = I.ANIMAL_ID
WHERE I.ANIMAL_ID IS NULL
ORDER BY O.ANIMAL_ID;

-- 있었는데요 없었습니다: JOIN으로 합친 뒤 두 테이블의 열을 직접 비교
-- (세금계산서 발행일이 실제 거래일보다 앞선 이상 데이터를 찾는 것과 같은 패턴)
SELECT I.ANIMAL_ID, I.NAME
FROM ANIMAL_INS I
JOIN ANIMAL_OUTS O ON I.ANIMAL_ID = O.ANIMAL_ID
WHERE I.DATETIME > O.DATETIME
ORDER BY I.DATETIME ASC;
