-- 출처: 프로그래머스 SQL 고득점 Kit

-- 아픈 동물 찾기: 조건에 맞는 행만 필터링
SELECT ANIMAL_ID, NAME
FROM ANIMAL_INS
WHERE INTAKE_CONDITION != 'Healthy'
ORDER BY ANIMAL_ID;

-- 어린 동물 찾기: != 와 <> 는 같은 의미(같지 않다)
SELECT ANIMAL_ID, NAME
FROM ANIMAL_INS
WHERE INTAKE_CONDITION <> 'Aged'
ORDER BY ANIMAL_ID;

-- 역순 정렬하기: ORDER BY ... DESC
SELECT NAME, DATETIME
FROM ANIMAL_INS
ORDER BY ANIMAL_ID DESC;
